const search = 'import { NextRequest } from "next/server"';
const replace = 'import { NextRequest, NextResponse } from "next/server"';

let fixed = 0;
let skipped = 0;
let missing = 0;

files.forEach(file => {
  const fullPath = path.join(process.cwd(), file);
  if (!fs.existsSync(fullPath)) {
    console.log('MISSING:', file);
    missing++;
    return;
  }
  const content = fs.readFileSync(fullPath, 'utf8');
  const hasReqImport = content.includes(search);
  const hasRespImport = content.includes('NextResponse } from "next/server"');
  if (hasReqImport && !hasRespImport) {
    const newContent = content.replace(search, replace);
    fs.writeFileSync(fullPath, newContent);
    console.log('Fixed:', file);
    fixed++;
  } else {
    skipped++;
  }
});

console.log('\nDone. Fixed:', fixed, '| Skipped:', skipped, '| Missing:', missing);
